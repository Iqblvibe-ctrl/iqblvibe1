const STORAGE_KEY_BERITA = 'sidau_berita_aktivitas_v1';

export function loadBeritaListFromStorage(): BeritaAktivitas[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_BERITA);
    if (!raw) return INITIAL_BERITA_LIST;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
    return INITIAL_BERITA_LIST;
  } catch {
    return INITIAL_BERITA_LIST;
  }
}

export function saveBeritaListToStorage(list: BeritaAktivitas[]): void {
  try {
    localStorage.setItem(STORAGE_KEY_BERITA, JSON.stringify(list));
  } catch (e) {
    console.error('Gagal menyimpan berita aktivitas ke localStorage', e);
  }
}
